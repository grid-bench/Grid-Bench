"""Generate complete appendix count tables from the frozen offline analysis.

Run ``python paper/build_tables.py``. The four generated TeX files use the
manuscript's tablehead, TableStripe, task, booktabs, and tabularx definitions.
No source table, source campaign, score, or manuscript section is modified.
"""

from __future__ import annotations

import argparse

from build_figures import (
    DATA,
    LENGTHS,
    MODELS,
    NAMES,
    ROOT,
    TASKS,
    check_tables,
    file_hash,
    one,
    read_tables,
    select,
)

from spatial_worlds.eval.expanded_analysis_registry import (
    CELL_TRAJECTORIES,
    DIMENSION_TRAJECTORIES,
    TASK_TRAJECTORIES,
)

OUT = ROOT / "paper/tables"
WORKLOADS = {
    "metric_paint": (25, 100),
    "box_reflection": (16, 64, 256),
    "boundary_layer": (15, 60, 150),
    "occluded_mix": (6, 12, 30),
}


def tex_row(values: list[str]) -> str:
    return " & ".join(values) + r" \\"


def table(
    *,
    columns: str,
    headers: list[str],
    rows: list[list[str]],
    group_size: int,
    caption: str,
    label: str,
    source_hash: str,
) -> str:
    lines = [
        "% Generated by paper/build_tables.py; edit the generator, not this table.",
        f"% Source snapshot: {DATA.relative_to(ROOT)}/",
        f"% Source table SHA-256: {source_hash}",
        r"\begin{table*}[t]",
        r"\centering",
        r"\small",
        r"\begingroup",
        r"\setlength{\tabcolsep}{5pt}",
        r"\renewcommand{\arraystretch}{1.06}",
        r"\begin{tabularx}{\textwidth}{" + columns + "}",
        r"\toprule",
    ]
    for header in headers:
        lines.extend([r"\tablehead", header])
    lines.append(r"\midrule")
    for index, values in enumerate(rows):
        if index and index % group_size == 0:
            lines.append(r"\midrule")
        lines.append(r"\rowcolor{TableStripe}" if index % 2 == 0 else r"\rowcolor{white}")
        lines.append(tex_row(values))
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabularx}",
            r"\endgroup",
            r"\caption{" + caption + "}",
            r"\label{" + label + "}",
            r"\end{table*}",
            "",
        ]
    )
    return "\n".join(lines)


def task_table(tables: dict[str, list[dict]]) -> str:
    rows = []
    for family, task_name in TASKS.items():
        for model in MODELS:
            points = select(tables["task_length"], family=family, model=model)
            assert [point["T"] for point in points] == list(LENGTHS)
            assert all(point["n"] == TASK_TRAJECTORIES for point in points)
            rows.append(
                [
                    r"\task{" + task_name + "}",
                    NAMES[model],
                    *[str(point["correct"]) for point in points],
                ]
            )
    assert len(rows) == len(TASKS) * len(MODELS)
    parts = []
    for offset in (0, 24):
        part = 1 + offset // 24
        parts.append(
            table(
                columns=r"ll*{6}{>{\centering\arraybackslash}X}",
                headers=[
                    tex_row(
                        [
                            r"\textbf{Rule}",
                            r"\textbf{Model}",
                            *[f"$T={length}$" for length in LENGTHS],
                        ]
                    )
                ],
                rows=rows[offset : offset + 24],
                group_size=len(MODELS),
                caption=(
                    "Complete task-specific semantic full-world exact-match counts. "
                    "For every rule, model, and event-sequence length, scored $=$ expected "
                    f"$={TASK_TRAJECTORIES}$ instances (three dimensions and "
                    f"{CELL_TRAJECTORIES} generated trajectories per dimension). Each entry "
                    "is a correct count, not a percentage; divide by "
                    f"{TASK_TRAJECTORIES} to obtain EM. Empty and invalid outcomes remain "
                    "in the denominator. "
                    "The six lengths are nested prefixes of the same trajectories but are "
                    "evaluated in separate model requests."
                ),
                label="tab:all-task-counts" + ("-2" if part == 2 else ""),
                source_hash=file_hash(DATA / "task_length.csv"),
            )
        )
    return "\n".join(parts)


def dimension_table(tables: dict[str, list[dict]]) -> str:
    rows = []
    for model in MODELS:
        for length in LENGTHS:
            points = [
                one(tables["dimension_length"], model=model, T=length, dimension=dimension)
                for dimension in (2, 3, 4)
            ]
            assert all(point["n"] == DIMENSION_TRAJECTORIES for point in points)
            rows.append(
                [
                    NAMES[model],
                    str(length),
                    *[str(point["correct"]) for point in points],
                    *[str(point["length_terminated"]) for point in points],
                ]
            )
    assert len(rows) == len(MODELS) * len(LENGTHS)
    return table(
        columns=r"lr*{6}{>{\centering\arraybackslash}X}",
        headers=[
            tex_row(
                [
                    r"\textbf{Model}",
                    "$T$",
                    r"\multicolumn{3}{c}{\textbf{Exact count}}",
                    r"\multicolumn{3}{c}{\textbf{Length-termination count}}",
                ]
            ),
            tex_row(["", "", "$d=2$", "$d=3$", "$d=4$", "$d=2$", "$d=3$", "$d=4$"]),
        ],
        rows=rows,
        group_size=6,
        caption=(
            "Complete dimension-specific exact-match and length-termination counts "
            "in the main view. For every model, dimension, and length, scored $=$ "
            "expected $=64$ instances (eight rules and eight trajectories per rule); "
            "all entries are counts over those 64 requests. Empty and invalid "
            "outcomes count as incorrect. Exactness and termination are different "
            "measurements of the same requests, not disjoint outcome categories: "
            "length termination need not imply an empty answer. Dimension jointly "
            "changes geometry, coordinate arity, and representation."
        ),
        label="tab:all-dimension-counts",
        source_hash=file_hash(DATA / "dimension_length.csv"),
    )


def workload_table(tables: dict[str, list[dict]], families: tuple[str, ...], name: str) -> str:
    rows = []
    for family in families:
        for workload in WORKLOADS[family]:
            for model in MODELS:
                points = select(tables["workload"], family=family, w=workload, model=model)
                assert [point["T"] for point in points] == list(LENGTHS)
                assert all(point["n"] == CELL_TRAJECTORIES for point in points)
                rows.append(
                    [
                        r"\task{" + TASKS[family] + "}",
                        str(workload),
                        NAMES[model],
                        *[str(point["correct"]) for point in points],
                        str(points[-1]["valid"]),
                    ]
                )
    assert len(rows) == sum(len(WORKLOADS[family]) for family in families) * len(MODELS)
    family_names = " and ".join(r"\task{" + TASKS[family] + "}" for family in families)
    return table(
        columns=r"lrl*{7}{>{\centering\arraybackslash}X}",
        headers=[
            tex_row(
                [
                    r"\textbf{Rule}",
                    "$w$",
                    r"\textbf{Model}",
                    r"\multicolumn{6}{c}{\textbf{Exact count at length }$T$}",
                    r"\textbf{Valid}",
                ]
            ),
            tex_row(["", "", "", *[f"${length}$" for length in LENGTHS], "$T=64$"]),
        ],
        rows=rows,
        group_size=len(MODELS),
        caption=(
            f"Complete workload-sweep counts for {family_names} at $d=2$. "
            "For every rule, model, workload target $w$, and length, scored $=$ "
            "expected $=8$ instances. The six exact-count columns include all "
            "failures; divide by eight to obtain EM. The final column counts valid "
            "states at $T=64$ among the same eight instances, including exact ones; "
            "zero means no valid state was returned, not a conditional accuracy. "
            "Workload targets are task-specific and do not guarantee an identical "
            "realized load for every event. Workload conditions use independently "
            "generated trajectories; the main-condition workload reuses existing "
            "main-view requests and is not extra replication."
        ),
        label=f"tab:all-workload-{name}",
        source_hash=file_hash(DATA / "workload.csv"),
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check-only",
        action="store_true",
        help="Check counts and generated-file consistency without writing.",
    )
    args = parser.parse_args()
    paths = [
        DATA / f"{name}.csv" for name in ("length", "task_length", "dimension_length", "workload")
    ]
    before = {path: file_hash(path) for path in paths}
    tables = read_tables()
    check_tables(tables)
    for family, workloads in WORKLOADS.items():
        assert {row["w"] for row in tables["workload"] if row["family"] == family} == set(workloads)
    products = {
        "all-task-counts.tex": task_table(tables),
        "all-dimension-counts.tex": dimension_table(tables),
        "all-workload-geometry.tex": workload_table(
            tables, ("metric_paint", "box_reflection"), "geometry"
        ),
        "all-workload-connectivity.tex": workload_table(
            tables, ("boundary_layer", "occluded_mix"), "connectivity"
        ),
    }
    if args.check_only:
        for name, content in products.items():
            assert (OUT / name).read_text(encoding="utf-8") == content, (
                f"Stale generated table: {name}"
            )
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, content in products.items():
            (OUT / name).write_text(content, encoding="utf-8")
    assert {path: file_hash(path) for path in paths} == before, (
        "Source table changed during generation."
    )
    print("Verified 48 task rows, 36 dimension rows, and 66 workload rows across four TeX files.")


if __name__ == "__main__":
    main()
